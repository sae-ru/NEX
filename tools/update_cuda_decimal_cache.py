"""Regenerate the CUDA binary64 cache from the pinned, unmodified Dragonbox copy."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]

def generated():
    original=ROOT/'runtime/third_party/dragonbox/dragonbox.h'
    source=original.read_text()
    part=source.split('struct cache_holder<ieee754_binary64> {',1)[1].split('};',1)[0]
    pairs=re.findall(r'\{(0x[0-9a-f]+), (0x[0-9a-f]+)\}',part)
    assert len(pairs)==619
    license=(ROOT/'runtime/third_party/dragonbox/LICENSE-Boost').read_text()
    notice='// Copyright 2020-2022 Junekey Jeon\n// Adapted from Dragonbox1.1.3.\n'
    notice+='// Source SHA256: '+hashlib.sha256(original.read_bytes()).hexdigest()+'\n'
    notice+='\n'.join('// '+line if line else '//' for line in license.splitlines())+'\n'
    values='\n'.join('{'+a+'ULL,'+b+'ULL},'for a,b in pairs)
    return '''#pragma once
#include <string_view>
namespace nex::cuda_detail {
// Generated by tools/update_cuda_decimal_cache.py; do not edit the table.
inline constexpr std::string_view decimalCache=R"nexdec(
'''+notice+'''struct NexDecimal128 {unsigned long long high,low;};
#if defined(__CUDACC_RTC__) || (defined(__CUDACC__) && !defined(__clang__))
__device__ __constant__
#elif defined(__CUDA_ARCH__)
__attribute__((device,constant))
#endif
static const NexDecimal128 nex_decimal_cache[619]={
'''+values+'''\n};
)nexdec";
}
'''

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=ROOT/'src/cuda_decimal_cache.h';text=generated()
    if args.check:
        if path.read_text()!=text:raise SystemExit('CUDA Dragonbox cache differs from its pinned source')
    else:path.write_text(text)
