"""Generate the bounded current status from the maintained README status section."""
import argparse
import json
import os
from pathlib import Path
import re
from urllib.parse import urlsplit

ROOT=Path(__file__).resolve().parents[1]
MAX_BYTES=6144


def generated():
    version_file=ROOT/'VERSION'
    if version_file.is_file():
        toolchain=version_file.read_text().strip()
        if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+',toolchain):raise ValueError('VERSION is not a semantic version')
    else:
        cmake=(ROOT/'CMakeLists.txt').read_text()
        toolchain=re.search(r'project\(NEX VERSION ([0-9.]+)\b',cmake)[1]
    language=json.loads((ROOT/'llm/language-pack.json').read_text())['language_version']
    declared=re.search(r'\blanguageVersion\s*=\s*"([^"]+)"',(ROOT/'include/nex/language.h').read_text())[1]
    if language!=declared:raise ValueError('language pack and compiler header disagree')
    readme=(ROOT/'README.md').read_text()
    section=readme.split('## Development status\n',1)[1].split('## Build and use\n',1)[0].strip()
    if f'toolchain {toolchain} / language {language}'not in section:raise ValueError('README status versions disagree with source')
    def link(match):
        label,target=match.groups();parts=urlsplit(target)
        if parts.scheme or target.startswith(('/', '#')):return match[0]
        path=Path(os.path.relpath(ROOT/parts.path,ROOT/'docs')).as_posix()
        if parts.fragment:path+='#'+parts.fragment
        return '['+label+']('+path+')'
    section=re.sub(r'\[([^\]]+)\]\(([^)]+)\)',link,section)
    text=f'''---
status: current
applies_to: "language {language}; toolchain {toolchain}"
owner: repository
generated_from: README.md#development-status
---

# Current NEX status

This bounded summary is generated by `python3 tools/current_status.py`.
It reports recorded evidence, not a live observation of devices or remote jobs.
For syntax and capabilities, query the selected compiler. For detailed history,
use [STATUS](../STATUS.md); for next work, use [development priorities](development-priorities.md).

{section}
'''
    if len(text.encode('utf-8'))>MAX_BYTES:raise ValueError('current status exceeds6144 bytes; shorten the source summary')
    return text


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=ROOT/'docs/STATUS.current.md';text=generated()
    if args.check:
        if not path.is_file()or path.read_text()!=text:raise SystemExit('current status is stale; run python3 tools/current_status.py')
    else:path.write_text(text)
