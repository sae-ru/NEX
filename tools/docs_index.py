#!/usr/bin/env python3
"""Generate the documentation index and check local links/current versions."""
import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT=Path(__file__).resolve().parents[1]
DOCS=ROOT/'docs'
INDEX=DOCS/'INDEX.md'
LINK=re.compile(r'!?\[([^\]]*)\]\(([^)\s]+)(?:\s+"[^"]*")?\)')
VERSION=re.compile(r'\btoolchain\s+([0-9]+(?:\.[0-9]+)*)')
LANGUAGE=re.compile(r'\blanguage\s+([0-9]+(?:\.[0-9]+)*)')


def current_versions():
    cmake=(ROOT/'CMakeLists.txt').read_text()
    toolchain=re.search(r'project\(NEX VERSION ([0-9.]+)\b',cmake)[1]
    language=json.loads((ROOT/'llm/language-pack.json').read_text())['language_version']
    return toolchain,language


def version_tuple(text):
    return tuple(int(part) for part in text.split('.') if part.isdigit())


def front_matter(text):
    if not text.startswith('---\n'):return {}
    end=text.find('\n---\n',4)
    if end<0:return {}
    values={}
    for line in text[4:end].splitlines():
        key,separator,value=line.partition(':')
        if separator:values[key.strip()]=value.strip().strip('"').strip("'")
    return values


def title(text,path):
    for line in text.splitlines():
        if line.startswith('# '):
            value=line[2:].strip()
            value=re.sub(r'[*_`]','',value)
            return value or path.stem
    return path.stem


def entries():
    found=[]
    for path in sorted(DOCS.rglob('*.md')):
        if path==INDEX:continue
        relative=path.relative_to(DOCS)
        text=path.read_text(errors='replace')
        meta=front_matter(text)
        found.append({'path':relative.as_posix(),'title':title(text,path),
            'status':meta.get('status','reference'),'applies_to':meta.get('applies_to',''),
            'owner':meta.get('owner','')})
    return found


def render(items,toolchain,language):
    groups=[('current','Current contracts'),
        ('deferred','Deferred'),
        ('historical','Historical'),
        ('reference','Reference and history')]
    lines=['# Documentation index','',
        f'Generated by `python3 tools/docs_index.py` for toolchain {toolchain} / language {language}.',
        'Do not edit this file by hand; regenerate it after adding or renaming a document.','',
        'The index is deliberately bounded navigation, not a claim that every linked',
        'document describes current behavior. Query the selected compiler for actual',
        'capabilities; `status: current` documents are checked against the current',
        'language and toolchain by the same script.','']
    counts={}
    for status,heading in groups:
        selected=[item for item in items if (item['status']=='reference' if status=='reference' else item['status']==status)]
        counts[status]=len(selected)
        lines.append(f'## {heading} ({len(selected)})')
        lines.append('')
        if not selected:
            lines.append('_None._')
            lines.append('')
            continue
        lines.append('| Document | Applies to | Owner |')
        lines.append('|---|---|---|')
        for item in sorted(selected,key=lambda entry:(entry['title'].casefold(),entry['path'])):
            label=item['title'].replace('|','\\|')
            applies=item['applies_to'].replace('|','\\|') or '—'
            owner=item['owner'].replace('|','\\|') or '—'
            lines.append(f'| [{label}]({item["path"]}) | {applies} | {owner} |')
        lines.append('')
    lines.append('## Totals')
    lines.append('')
    lines.append(f'{len(items)} documents: {counts["current"]} current, {counts["deferred"]} deferred, '
        f'{counts["historical"]} historical, {counts["reference"]} reference/unclassified.')
    lines.append('')
    return '\n'.join(lines)


def local_links(path):
    text=path.read_text(errors='replace')
    missing=[]
    checked=0
    for _label,target in LINK.findall(text):
        if target.startswith(('http://','https://','mailto:','data:','#')):continue
        parts=urlsplit(target)
        if parts.scheme:continue
        relative=unquote(parts.path)
        if not relative:continue
        checked+=1
        resolved=(ROOT/relative.lstrip('/')) if relative.startswith('/') else (path.parent/relative)
        if not resolved.exists():missing.append({'document':str(path.relative_to(ROOT)),'target':target})
    return checked,missing


def version_errors(items,toolchain,language):
    errors=[]
    for item in items:
        if item['status'] not in ('current','deferred'):continue
        applies=item['applies_to']
        found_language=LANGUAGE.search(applies)
        found_toolchain=VERSION.search(applies)
        if found_language and found_language[1]!=language:
            errors.append({'document':item['path'],'reason':'applies_to language differs from the compiler',
                'expected':language,'actual':found_language[1]})
        if found_toolchain and version_tuple(found_toolchain[1])>version_tuple(toolchain):
            errors.append({'document':item['path'],'reason':'applies_to toolchain is newer than the compiler',
                'expected':toolchain,'actual':found_toolchain[1]})
        if item['status']=='current' and not found_language and not found_toolchain:
            errors.append({'document':item['path'],'reason':'current document lacks language/toolchain applicability'})
        if item['status']=='current' and not item['owner']:
            errors.append({'document':item['path'],'reason':'current document lacks an owner'})
    return errors


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='verify the generated index, links and current versions')
    parser.add_argument('--write',action='store_true',help='regenerate docs/INDEX.md')
    args=parser.parse_args()
    if args.check==args.write:parser.error('select exactly one of --check or --write')
    toolchain,language=current_versions()
    items=entries()
    generated=render(items,toolchain,language)
    result={'schema':'nex.documentation-index/1','toolchain':toolchain,'language':language,
        'documents':len(items),'index':str(INDEX.relative_to(ROOT)),'errors':[]}
    if args.write:
        INDEX.write_text(generated)
        result['written']=True
    else:
        if not INDEX.is_file():
            result['errors'].append({'document':'docs/INDEX.md','reason':'missing generated index'})
        elif INDEX.read_text()!=generated:
            result['errors'].append({'document':'docs/INDEX.md','reason':'index is stale; run tools/docs_index.py --write'})
        checked=0;missing=[]
        for path in sorted(DOCS.rglob('*.md'))+[ROOT/'README.md',ROOT/'README.ru.md',ROOT/'llms.txt',ROOT/'AGENTS.md']:
            count,absent=local_links(path)
            checked+=count;missing.extend(absent)
        result['links_checked']=checked
        result['missing_links']=missing
        result['errors'].extend({'document':item['document'],'reason':'missing local link target','target':item['target']} for item in missing)
        result['errors'].extend(version_errors(items,toolchain,language))
        status=subprocess.run([sys.executable,str(ROOT/'tools/current_status.py'),'--check'],cwd=ROOT,capture_output=True,text=True)
        if status.returncode!=0:
            result['errors'].append({'document':'docs/STATUS.current.md','reason':status.stderr.strip() or 'current status is stale'})
        result['current_status_ok']=status.returncode==0
    result['ok']=not result['errors']
    print(json.dumps(result,indent=2))
    return 0 if result['ok'] else 1


if __name__=='__main__':raise SystemExit(main())
